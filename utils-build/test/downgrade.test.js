'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const loadLegacySodium = require('./load-legacy-sodium.js');
const compat = require('../sodium-compat.js');

test('Scenario 14: Bidirectional downgrade compatibility check', (t) => {
  const legacy = loadLegacySodium();
  if (!legacy) {
    t.skip('Legacy libsodium not available for downgrade check');
    return;
  }

  // 1. Create wallet artifacts using ONLY sodium-compat (the new shim)
  const pin = '482619';
  const passphrase = 'noble compatibility test';
  const recoveryphrase = 'alpha beta gamma delta epsilon zeta eta theta iota kappa';
  const testSeed = 'sp5fV4UGhZhfCvcDRuY3dyyh5PjHf';

  function compatToHexChk(data) {
    if (typeof data === 'string') data = compat.from_string(data);
    return compat.crypto_generichash(4, data, '', 'hex') + compat.to_hex(data);
  }

  function legacyFromHexChk(hex, format) {
    const chksum = hex.slice(0, 8);
    const payload = legacy.from_hex(hex.slice(8));
    if (legacy.crypto_generichash(4, payload, '', 'hex') !== chksum) return false;
    if (format === 'string') return legacy.to_string(payload);
    return payload;
  }

  // Pin data written by compat
  const pinSalt = compat.randombytes_buf(32);
  const pinHash = compat.crypto_pwhash_scryptsalsa208sha256(32, pin, pinSalt, 4, 33554432);
  const pindata = {
    salt: compatToHexChk(pinSalt),
    hash: compatToHexChk(pinHash)
  };

  // Passphrase data written by compat
  const ppsalt1 = compat.randombytes_buf(32);
  const ppsalt2 = compat.randombytes_buf(32);
  const sec16 = compat.crypto_pwhash_scryptsalsa208sha256(16, passphrase, ppsalt1, 4, 33554432);
  const pphash = compat.crypto_pwhash_scryptsalsa208sha256(16, sec16, ppsalt2, 4, 33554432);
  const ppdata = {
    salt1: compatToHexChk(ppsalt1),
    salt2: compatToHexChk(ppsalt2),
    hash: compatToHexChk(pphash)
  };

  // Account encrypted by compat
  const accSalt = compat.randombytes_buf(32);
  const accKey32 = compat.crypto_pwhash_scryptsalsa208sha256(32, sec16, accSalt, 4, 33554432);
  const nonce = compat.randombytes_buf(24);
  const ctHex = compat.crypto_secretbox_easy(testSeed, nonce, accKey32, 'hex');
  const storedSecret = compatToHexChk(compat.from_hex(compat.to_hex(nonce) + ctHex));

  // Backup code generated by compat
  const exportPayload = JSON.stringify({
    walletversion: '1.0',
    pindata,
    ppdata,
    accounts: {
      rTest: {
        ppsalt: compatToHexChk(accSalt),
        ppsecret: storedSecret
      }
    }
  });
  const backupCode = compat.crypto_generichash(4, exportPayload, '', 'hex') + exportPayload;

  // 2. NOW VERIFY EVERYTHING USING ONLY LEGACY LIBSODIUM 1.0.13
  // Unlock with legacy sodium
  const legacySalt = legacyFromHexChk(pindata.salt);
  const legacyHash = legacy.crypto_pwhash_scryptsalsa208sha256(32, pin, legacySalt, 4, 33554432);
  const legacyHashFormatted = legacy.crypto_generichash(4, legacyHash, '', 'hex') + legacy.to_hex(legacyHash);
  assert.equal(legacyHashFormatted, pindata.hash, 'Legacy sodium failed to unlock compat PIN');

  // Verify passphrase with legacy sodium
  const legPpSalt1 = legacyFromHexChk(ppdata.salt1);
  const legPpSalt2 = legacyFromHexChk(ppdata.salt2);
  const legSec16 = legacy.crypto_pwhash_scryptsalsa208sha256(16, passphrase, legPpSalt1, 4, 33554432);
  const legPphash = legacy.crypto_pwhash_scryptsalsa208sha256(16, legSec16, legPpSalt2, 4, 33554432);
  const legPpHashFormatted = legacy.crypto_generichash(4, legPphash, '', 'hex') + legacy.to_hex(legPphash);
  assert.equal(legPpHashFormatted, ppdata.hash, 'Legacy sodium failed to verify compat passphrase');

  // Decrypt account secret with legacy sodium
  const legAccSalt = legacyFromHexChk(compatToHexChk(accSalt));
  const legAccKey32 = legacy.crypto_pwhash_scryptsalsa208sha256(32, legSec16, legAccSalt, 4, 33554432);
  const legRawSecret = legacyFromHexChk(storedSecret);
  const legNonce = legRawSecret.slice(0, 24);
  const legCt = legRawSecret.slice(24);
  const legDecryptedSeed = legacy.to_string(legacy.crypto_secretbox_open_easy(legCt, legNonce, legAccKey32));
  assert.equal(legDecryptedSeed, testSeed, 'Legacy sodium failed to decrypt compat account secret');

  // Verify backup code with legacy sodium
  const bHash = backupCode.slice(0, 8);
  const bJson = backupCode.slice(8);
  const legBackupHash = legacy.crypto_generichash(4, bJson, '', 'hex');
  assert.equal(bHash, legBackupHash, 'Legacy sodium failed to verify compat backup checksum');
});
